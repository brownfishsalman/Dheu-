const num = (v) => Number(v);
const fmt = (n) => (Math.round(n * 1000) / 1000).toString();

// SVG primitive -> path data string
function toPath([tag, a]) {
  switch (tag) {
    case "path":
      return a.d;
    case "circle": {
      const cx = num(a.cx), cy = num(a.cy), r = num(a.r);
      return `M${fmt(cx - r)} ${fmt(cy)}a${fmt(r)} ${fmt(r)} 0 1 0 ${fmt(2 * r)} 0a${fmt(r)} ${fmt(r)} 0 1 0 ${fmt(-2 * r)} 0`;
    }
    case "ellipse": {
      const cx = num(a.cx), cy = num(a.cy), rx = num(a.rx), ry = num(a.ry);
      return `M${fmt(cx - rx)} ${fmt(cy)}a${fmt(rx)} ${fmt(ry)} 0 1 0 ${fmt(2 * rx)} 0a${fmt(rx)} ${fmt(ry)} 0 1 0 ${fmt(-2 * rx)} 0`;
    }
    case "line":
      return `M${a.x1} ${a.y1}L${a.x2} ${a.y2}`;
    case "polyline":
    case "polygon": {
      const pts = a.points.trim().split(/[\s,]+/).map(num);
      let d = `M${pts[0]} ${pts[1]}`;
      for (let i = 2; i < pts.length; i += 2) d += `L${pts[i]} ${pts[i + 1]}`;
      return tag === "polygon" ? d + "Z" : d;
    }
    case "rect": {
      const x = num(a.x ?? 0), y = num(a.y ?? 0), w = num(a.width), h = num(a.height);
      const rx = Math.min(num(a.rx ?? a.ry ?? 0), w / 2), ry = Math.min(num(a.ry ?? a.rx ?? 0), h / 2);
      if (!rx) return `M${x} ${y}H${x + w}V${y + h}H${x}Z`;
      return (
        `M${fmt(x + rx)} ${y}H${fmt(x + w - rx)}A${rx} ${ry} 0 0 1 ${x + w} ${fmt(y + ry)}V${fmt(y + h - ry)}` +
        `A${rx} ${ry} 0 0 1 ${fmt(x + w - rx)} ${y + h}H${fmt(x + rx)}A${rx} ${ry} 0 0 1 ${x} ${fmt(y + h - ry)}` +
        `V${fmt(y + ry)}A${rx} ${ry} 0 0 1 ${fmt(x + rx)} ${y}Z`
      );
    }
    default:
      throw new Error(`Unsupported SVG element <${tag}>`);
  }
}

// Some names are aliases ("export { default } from './trash.mjs'"); follow them.
async function iconData(file) {
  for (let hops = 0; hops < 5; hops++) {
    const path = join(iconsDir, `${file}.mjs`);
    const alias = readFileSync(path, "utf8").match(/export \{ default \} from '\.\/([\w-]+)\.mjs'/);
    if (!alias) return (await import(pathToFileURL(path).href)).__iconData;
    file = alias[1];
  }
  throw new Error(`Alias loop at ${file}`);
}

const version = JSON.parse(readFileSync(join(lucideDir, "package.json"), "utf8")).version;
const lines = [];
for (const [kotlinName, file] of Object.entries(ICONS)) {
  const paths = (await iconData(file)).node.map(toPath).map((d) => JSON.stringify(d));
  const builder = kotlinName.endsWith("Filled") ? "lucideFilled" : "lucide";
  lines.push(`    val ${kotlinName}: ImageVector by lazy { ${builder}("${kotlinName}", ${paths.join(", ")}) }`);
}

const kotlin = `// Generated by android/tools/generate-icons.mjs from lucide-react ${version}
// (ISC licence, https://lucide.dev). Do not edit by hand; rerun the script.
package com.salmansaadiq.dheu.ui.icons

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.SolidColor
import androidx.compose.ui.graphics.StrokeCap
import androidx.compose.ui.graphics.StrokeJoin
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.graphics.vector.addPathNodes
import androidx.compose.ui.unit.dp

object Lucide {
${lines.join("\n")}
}

private fun lucide(name: String, vararg paths: String) = icon(name, filled = false, paths)

private fun lucideFilled(name: String, vararg paths: String) = icon(name, filled = true, paths)

private fun icon(name: String, filled: Boolean, paths: Array<out String>): ImageVector =
    ImageVector.Builder(name = name, defaultWidth = 24.dp, defaultHeight = 24.dp, viewportWidth = 24f, viewportHeight = 24f)
        .apply {
            for (d in paths) {
                addPath(
                    pathData = addPathNodes(d),
                    fill = if (filled) SolidColor(Color.Black) else null,
                    stroke = SolidColor(Color.Black),
                    strokeLineWidth = 2f,
                    strokeLineCap = StrokeCap.Round,
                    strokeLineJoin = StrokeJoin.Round,
                )
            }
        }
        .build()
`;

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, kotlin);
console.log(`wrote ${Object.keys(ICONS).length} icons to ${out}`);
